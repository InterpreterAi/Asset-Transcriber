const ENGLISH_COLLOQUIAL_TO_STANDARD: readonly [string, string][] = [
  ["gonna", "going to"],
  ["wanna", "want to"],
  ["gotta", "have to"],
  ["ain't", "is not"],
];

function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function replaceStandalone(
  text: string,
  from: string,
  to: string,
  script: "ar" | "en",
): string {
  const body = escapeRegex(from);
  if (script === "en") {
    const re = new RegExp(`(?<![A-Za-z])${body}(?![A-Za-z])`, "gi");
    return text.replace(re, to);
  }
  // Allow optional clitics و/ف/ب/ك/ل so "وهنجيب" still rewrites.
  const re = new RegExp(
    `(^|[^\\u0600-\\u06FF]|[وفبكل])${body}(?![\\u0600-\\u06FF])`,
    "g",
  );
  return text.replace(re, (_m, prefix: string) => `${prefix}${to}`);
}

function applyPairs(
  text: string,
  pairs: readonly [string, string][],
  script: "ar" | "en",
): string {
  let out = text;
  for (const [from, to] of pairs) {
    out = replaceStandalone(out, from, to, script);
  }
  return out;
}

/** Rewrite leaked dialect in the translation column into the official target register. */
export function lockTranslationToOfficialRegister(
  text: string,
  targetBase: string,
): string {
  if (!text.trim()) return text;
  const base = targetBase.split("-")[0]!.toLowerCase();
  if (base === "ar") {
    return applyPairs(text, ARABIC_DIALECT_TO_MSA, "ar").replace(/\s{2,}/g, " ").trim();
  }
  if (base === "en") return applyPairs(text, ENGLISH_COLLOQUIAL_TO_STANDARD, "en");
  return text;
}
