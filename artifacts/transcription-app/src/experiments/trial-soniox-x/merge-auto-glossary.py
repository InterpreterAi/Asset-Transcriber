PAIR_LANG = {
  "en-ar": "ar",
  "en-es": "es",
  "en-pt": "pt",
  "en-pl": "pl",
  "en-de": "de",
  "en-it": "it",
}


def main() -> None:
  path = Path(__file__).with_name("interpreter-glossary.json")
  data = json.loads(path.read_text())
  pairs = data.setdefault("pairs", {})

  added: dict[str, int] = {}
  for pair_key, lang in PAIR_LANG.items():
    rows = pairs.setdefault(pair_key, [])
    existing = {str(r.get("en", "")).strip().lower() for r in rows}
    n = 0
    for item in AUTO:
      en = item["en"].strip()
      tgt = item[lang].strip()
      if not en or not tgt:
        continue
      if en.lower() in existing:
        continue
      rows.append({"en": en, lang: tgt})
      existing.add(en.lower())
      n += 1
    added[pair_key] = n

  path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
  print("added", added)
  for k in PAIR_LANG:
    print(k, "total", len(pairs[k]))


if __name__ == "__main__":
  main()
