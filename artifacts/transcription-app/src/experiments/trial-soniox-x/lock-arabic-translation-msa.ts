const RULES = [...ARABIC_DIALECT_TO_MSA]
  .sort((a, b) => b[0].length - a[0].length)
  .map(([from, to]) => ({
    from,
    to,
    re: new RegExp(`(^|[^\\p{L}]|[وفبكل])${escapeRegex(from)}(?![\\p{L}])`, "gu"),
  }));

const AR_SCRIPT = /[\u0600-\u06FF]/;

/**
 * Fast no-op when the translation is already فصحى or not Arabic.
 * Precompiled regexes; skip a rule when `from` is absent.
 */
export function lockArabicTranslationToMsa(text: string): string {
  if (!text || !AR_SCRIPT.test(text)) return text;
  let out = text;
  let changed = false;
  for (const rule of RULES) {
    if (!out.includes(rule.from)) continue;
    rule.re.lastIndex = 0;
    const next = out.replace(rule.re, (_m, prefix: string) => `${prefix}${rule.to}`);
    if (next !== out) {
      out = next;
      changed = true;
    }
  }
  if (!changed) return text;
  return out.replace(/\s{2,}/g, " ");
}
