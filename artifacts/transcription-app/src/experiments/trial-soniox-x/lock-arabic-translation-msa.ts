/**
 * Only و/ف may attach, and only to words of 4+ letters: shorter words glued to a
 * prefix are real فصحى words (لدي، فيلا، كشوف، بما في). Harakat count as part of
 * the word, so تمامًا is never split.
 */
function prefixFor(from: string): string {
  if (/^\s/.test(from)) return "(^|[^\\p{L}]|[وفبكل])";
  return from.length >= 4 ? "(^|[^\\p{L}\\p{M}]|[وف])" : "(^|[^\\p{L}\\p{M}])";
}

const RULES = [...ARABIC_DIALECT_TO_MSA]
  .sort((a, b) => b[0].length - a[0].length)
  .map(([from, to]) => ({
    from,
    to,
    re: new RegExp(`${prefixFor(from)}${escapeRegex(from)}(?![\\p{L}\\p{M}])`, "gu"),
  }));

const AR_SCRIPT = /[\u0600-\u06FF]/;

/**
 * Fast no-op when the translation is already فصحى or not Arabic.
 * Precompiled regexes; skip a rule when `from` is absent.
 * Always safe on the TRANSLATION column — never call on Original.
 */
export function lockArabicTranslationToMsa(text: string): string {
  if (!text || !AR_SCRIPT.test(text)) return text;
  let out = text;
  let changed = false;
  for (const rule of RULES) {
    if (!out.includes(rule.from)) continue;
    rule.re.lastIndex = 0;
    const next = out.replace(rule.re, (_m, prefix: string) => `${prefix}${rule.to}`);
    if (next !== out) {
      out = next;
      changed = true;
    }
  }
  // Leading بس… (no space prefix for the " بس" rule)
  if (/(^|[،,])\s*بس\b/u.test(out)) {
    const next = out.replace(/(^|[،,])(\s*)بس(?=[\s،,]|$)/gu, "$1$2لكن");
    if (next !== out) {
      out = next;
      changed = true;
    }
  }
  if (!changed) return text;
  return out.replace(/\s{2,}/g, " ").trim();
}
